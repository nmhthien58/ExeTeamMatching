-- BE-01 – academic_db (Academic Service). Thiết kế: docs/EXE_Database_Design.pdf mục 5.
\connect academic_db

CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS btree_gist;   -- EXCLUDE chống chồng đợt đăng ký
CREATE SCHEMA IF NOT EXISTS academic AUTHORIZATION academic_svc;
SET ROLE academic_svc;
SET search_path = academic, public;

CREATE OR REPLACE FUNCTION academic.set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END $$;

-- ---------- Danh mục (rule 12) ----------
CREATE TABLE academic.specializations (
    id         integer      GENERATED BY DEFAULT AS IDENTITY,
    code       varchar(20)  NOT NULL,
    name       varchar(100) NOT NULL,
    is_active  boolean      NOT NULL DEFAULT true,
    created_at timestamptz  NOT NULL DEFAULT now(),
    updated_at timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_specializations PRIMARY KEY (id),
    CONSTRAINT uq_specializations_code UNIQUE (code),
    CONSTRAINT ck_specializations_code CHECK (code ~ '^[A-Z0-9_]{2,20}$')
);

CREATE TABLE academic.domains (
    id          integer      GENERATED BY DEFAULT AS IDENTITY,
    code        varchar(3)   NOT NULL,
    name        varchar(150) NOT NULL,
    description varchar(500),
    is_active   boolean      NOT NULL DEFAULT true,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_domains PRIMARY KEY (id),
    CONSTRAINT uq_domains_code UNIQUE (code),
    CONSTRAINT ck_domains_code CHECK (code ~ '^D(0[1-9]|1[0-8])$')
);

CREATE TABLE academic.class_codes (
    id         integer     GENERATED BY DEFAULT AS IDENTITY,
    code       varchar(20) NOT NULL,
    is_active  boolean     NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_class_codes PRIMARY KEY (id),
    CONSTRAINT uq_class_codes_code UNIQUE (code),
    CONSTRAINT ck_class_codes_code CHECK (code ~ '^[A-Z0-9]{3,20}$')
);

-- ---------- Học kỳ, đợt đăng ký (rule 6) ----------
CREATE TABLE academic.semesters (
    id         uuid        NOT NULL DEFAULT gen_random_uuid(),
    code       varchar(4)  NOT NULL,
    name       varchar(50) NOT NULL,
    start_date date        NOT NULL,
    end_date   date        NOT NULL,
    is_current boolean     NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_semesters PRIMARY KEY (id),
    CONSTRAINT uq_semesters_code UNIQUE (code),
    CONSTRAINT ck_semesters_code CHECK (code ~ '^(SP|SU|FA)[0-9]{2}$'),
    CONSTRAINT ck_semesters_dates CHECK (end_date > start_date)
);
CREATE UNIQUE INDEX uq_semesters_is_current ON academic.semesters (is_current) WHERE is_current;

CREATE TABLE academic.registration_rounds (
    id          uuid         NOT NULL DEFAULT gen_random_uuid(),
    semester_id uuid         NOT NULL,
    course_code varchar(6)   NOT NULL,
    round_type  varchar(20)  NOT NULL,
    name        varchar(100) NOT NULL,
    opens_at    timestamptz  NOT NULL,
    deadline_at timestamptz  NOT NULL,
    status      varchar(10)  NOT NULL DEFAULT 'SCHEDULED',
    closed_at   timestamptz,
    created_by  uuid         NOT NULL,          -- identity.user_accounts.id (claim sub)
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_registration_rounds PRIMARY KEY (id),
    CONSTRAINT fk_registration_rounds_semester FOREIGN KEY (semester_id)
        REFERENCES academic.semesters (id) ON DELETE RESTRICT,
    CONSTRAINT ck_registration_rounds_course CHECK (course_code IN ('EXE101', 'EXE201')),
    CONSTRAINT ck_registration_rounds_type CHECK (round_type IN ('TEAM_FORMATION', 'CHANGE_REQUEST')),
    CONSTRAINT ck_registration_rounds_course_type CHECK (round_type <> 'CHANGE_REQUEST' OR course_code = 'EXE201'),
    CONSTRAINT ck_registration_rounds_status CHECK (status IN ('SCHEDULED', 'OPEN', 'CLOSED')),
    CONSTRAINT ck_registration_rounds_closed CHECK ((status = 'CLOSED') = (closed_at IS NOT NULL)),
    CONSTRAINT ck_registration_rounds_window CHECK (deadline_at > opens_at),
    CONSTRAINT ex_registration_rounds_overlap EXCLUDE USING gist (
        semester_id WITH =, course_code WITH =, round_type WITH =,
        tstzrange(opens_at, deadline_at, '[)') WITH &&)
);
CREATE INDEX idx_registration_rounds_semester_id ON academic.registration_rounds (semester_id);
CREATE INDEX idx_registration_rounds_open ON academic.registration_rounds (deadline_at) WHERE status = 'OPEN';

-- ---------- Sinh viên, giảng viên ----------
-- Hồ sơ sinh viên, ổn định qua các học kỳ (EXE101 -> EXE201). MSSV 2 chữ + 6 số, SĐT là chuỗi (rule 11).
CREATE TABLE academic.students (
    id                uuid          NOT NULL DEFAULT gen_random_uuid(),
    student_code      varchar(8)    NOT NULL,
    full_name         varchar(150)  NOT NULL,
    email             citext        NOT NULL,
    phone             varchar(15),
    specialization_id integer       NOT NULL,
    skills            varchar(50)[] NOT NULL DEFAULT '{}',
    bio               varchar(500),
    is_seeking_team   boolean       NOT NULL DEFAULT false,   -- công tắc "Tôi đang tìm nhóm" (S03)
    created_at        timestamptz   NOT NULL DEFAULT now(),
    updated_at        timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_students PRIMARY KEY (id),
    CONSTRAINT uq_students_student_code UNIQUE (student_code),
    CONSTRAINT uq_students_email UNIQUE (email),
    CONSTRAINT fk_students_specialization FOREIGN KEY (specialization_id)
        REFERENCES academic.specializations (id) ON DELETE RESTRICT,
    CONSTRAINT ck_students_student_code CHECK (student_code ~ '^[A-Z]{2}[0-9]{6}$'),
    CONSTRAINT ck_students_email CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT ck_students_phone CHECK (phone IS NULL OR phone ~ '^\+?[0-9]{9,14}$'),
    CONSTRAINT ck_students_skills_count CHECK (cardinality(skills) <= 20)
);
CREATE INDEX idx_students_specialization_id ON academic.students (specialization_id);
CREATE INDEX idx_students_full_name ON academic.students (lower(full_name));

-- Giảng viên do Admin nhập email (cấp role Lecturer qua sự kiện LecturerRegistered).
CREATE TABLE academic.lecturers (
    id                 uuid         NOT NULL DEFAULT gen_random_uuid(),
    full_name          varchar(150) NOT NULL,
    email              citext       NOT NULL,
    phone              varchar(15),
    expertise          varchar(300),                        -- lĩnh vực chuyên môn (S23, L06)
    max_teams          smallint     NOT NULL DEFAULT 8,      -- sức chứa (PROJECT_CONTEXT §5.3)
    is_accepting_teams boolean      NOT NULL DEFAULT true,   -- công tắc nhận nhóm mới (L06)
    is_active          boolean      NOT NULL DEFAULT true,
    created_at         timestamptz  NOT NULL DEFAULT now(),
    updated_at         timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_lecturers PRIMARY KEY (id),
    CONSTRAINT uq_lecturers_email UNIQUE (email),
    CONSTRAINT ck_lecturers_email CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT ck_lecturers_phone CHECK (phone IS NULL OR phone ~ '^\+?[0-9]{9,14}$'),
    CONSTRAINT ck_lecturers_max_teams CHECK (max_teams BETWEEN 1 AND 50)
);

-- ---------- Import (W06–W08) và danh sách sinh viên học kỳ (nguồn whitelist) ----------
CREATE TABLE academic.import_batches (
    id           uuid         NOT NULL DEFAULT gen_random_uuid(),
    semester_id  uuid         NOT NULL,
    file_name    varchar(255) NOT NULL,
    total_rows   integer      NOT NULL DEFAULT 0,
    success_rows integer      NOT NULL DEFAULT 0,
    failed_rows  integer      NOT NULL DEFAULT 0,
    errors       jsonb,                              -- [{row, field, message}]
    status       varchar(20)  NOT NULL DEFAULT 'PROCESSING',
    imported_by  uuid         NOT NULL,              -- identity.user_accounts.id
    created_at   timestamptz  NOT NULL DEFAULT now(),
    completed_at timestamptz,
    CONSTRAINT pk_import_batches PRIMARY KEY (id),
    CONSTRAINT fk_import_batches_semester FOREIGN KEY (semester_id)
        REFERENCES academic.semesters (id) ON DELETE RESTRICT,
    CONSTRAINT ck_import_batches_status CHECK (status IN ('PROCESSING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_import_batches_rows CHECK (total_rows >= 0 AND success_rows >= 0 AND failed_rows >= 0
        AND success_rows + failed_rows <= total_rows)
);
CREATE INDEX idx_import_batches_semester_id ON academic.import_batches (semester_id);

CREATE TABLE academic.semester_enrollments (
    id              uuid        NOT NULL DEFAULT gen_random_uuid(),
    semester_id     uuid        NOT NULL,
    student_id      uuid        NOT NULL,
    course_code     varchar(6)  NOT NULL,
    class_code_id   integer     NOT NULL,
    import_batch_id uuid,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_semester_enrollments PRIMARY KEY (id),
    CONSTRAINT uq_semester_enrollments_semester_student UNIQUE (semester_id, student_id),
    CONSTRAINT fk_semester_enrollments_semester FOREIGN KEY (semester_id)
        REFERENCES academic.semesters (id) ON DELETE RESTRICT,
    CONSTRAINT fk_semester_enrollments_student FOREIGN KEY (student_id)
        REFERENCES academic.students (id) ON DELETE RESTRICT,
    CONSTRAINT fk_semester_enrollments_class_code FOREIGN KEY (class_code_id)
        REFERENCES academic.class_codes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_semester_enrollments_import_batch FOREIGN KEY (import_batch_id)
        REFERENCES academic.import_batches (id) ON DELETE SET NULL,
    CONSTRAINT ck_semester_enrollments_course CHECK (course_code IN ('EXE101', 'EXE201'))
);
CREATE INDEX idx_semester_enrollments_student_id ON academic.semester_enrollments (student_id);
CREATE INDEX idx_semester_enrollments_class_code_id ON academic.semester_enrollments (class_code_id);
CREATE INDEX idx_semester_enrollments_import_batch ON academic.semester_enrollments (import_batch_id);

-- Cấu hình quy tắc (W05). Một dòng duy nhất (id = 1).
CREATE TABLE academic.rule_settings (
    id                      smallint    NOT NULL DEFAULT 1,
    min_team_size           smallint    NOT NULL DEFAULT 4,
    max_team_size           smallint    NOT NULL DEFAULT 6,
    min_specializations     smallint    NOT NULL DEFAULT 2,
    invitation_expiry_hours smallint    NOT NULL DEFAULT 72,
    reminder_hours          smallint[]  NOT NULL DEFAULT '{72,24}',
    updated_by              uuid,
    updated_at              timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_rule_settings PRIMARY KEY (id),
    CONSTRAINT ck_rule_settings_singleton CHECK (id = 1),
    CONSTRAINT ck_rule_settings_team_size CHECK (min_team_size >= 2 AND max_team_size >= min_team_size),
    CONSTRAINT ck_rule_settings_expiry CHECK (invitation_expiry_hours > 0)
);

-- ---------- Transactional Outbox ----------
-- StudentImported, StudentProfileUpdated, LecturerRegistered (topic exe.student); RoundOpened, RoundClosed (exe.registration).
CREATE TABLE academic.outbox_messages (
    id             uuid         NOT NULL,          -- = eventId của envelope
    topic          varchar(100) NOT NULL,
    event_type     varchar(100) NOT NULL,
    aggregate_type varchar(50)  NOT NULL,
    aggregate_id   uuid         NOT NULL,          -- Kafka message key
    payload        jsonb        NOT NULL,
    correlation_id varchar(64),
    occurred_at    timestamptz  NOT NULL DEFAULT now(),
    processed_at   timestamptz,
    attempts       integer      NOT NULL DEFAULT 0,
    last_error     text,
    CONSTRAINT pk_outbox_messages PRIMARY KEY (id),
    CONSTRAINT ck_outbox_messages_attempts CHECK (attempts >= 0)
);
CREATE INDEX idx_outbox_messages_pending ON academic.outbox_messages (occurred_at) WHERE processed_at IS NULL;

-- ---------- updated_at triggers ----------
CREATE TRIGGER trg_specializations_updated_at BEFORE UPDATE ON academic.specializations FOR EACH ROW EXECUTE FUNCTION academic.set_updated_at();
CREATE TRIGGER trg_domains_updated_at         BEFORE UPDATE ON academic.domains         FOR EACH ROW EXECUTE FUNCTION academic.set_updated_at();
CREATE TRIGGER trg_class_codes_updated_at     BEFORE UPDATE ON academic.class_codes     FOR EACH ROW EXECUTE FUNCTION academic.set_updated_at();
CREATE TRIGGER trg_semesters_updated_at       BEFORE UPDATE ON academic.semesters       FOR EACH ROW EXECUTE FUNCTION academic.set_updated_at();
CREATE TRIGGER trg_registration_rounds_updated_at BEFORE UPDATE ON academic.registration_rounds FOR EACH ROW EXECUTE FUNCTION academic.set_updated_at();
CREATE TRIGGER trg_students_updated_at        BEFORE UPDATE ON academic.students        FOR EACH ROW EXECUTE FUNCTION academic.set_updated_at();
CREATE TRIGGER trg_lecturers_updated_at       BEFORE UPDATE ON academic.lecturers       FOR EACH ROW EXECUTE FUNCTION academic.set_updated_at();
CREATE TRIGGER trg_rule_settings_updated_at   BEFORE UPDATE ON academic.rule_settings   FOR EACH ROW EXECUTE FUNCTION academic.set_updated_at();

RESET ROLE;
