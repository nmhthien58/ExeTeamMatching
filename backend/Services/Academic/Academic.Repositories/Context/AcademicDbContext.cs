using Academic.Repositories.Catalogs;
using Academic.Repositories.Imports;
using Academic.Repositories.Lecturers;
using Academic.Repositories.Mentors;
using Academic.Repositories.Rounds;
using Academic.Repositories.Semesters;
using Academic.Repositories.Settings;
using Academic.Repositories.Students;
using BuildingBlocks.Outbox;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Academic.Repositories.Context;

/// <summary>
/// DbContext của <c>academic_db</c> (schema <c>academic</c>, BE-15). Map đúng 15 bảng trong deploy/db/02_academic_db.sql:
/// tên cột snake_case qua UseSnakeCaseNamingConvention, tên bảng và khóa khai báo dưới đây.
/// Không dùng EF migration: DB tạo bằng script; đổi bảng thì sửa script trước (Thiên duyệt), rồi sửa file này cho khớp.
/// </summary>
public class AcademicDbContext(DbContextOptions<AcademicDbContext> options) : DbContext(options)
{
    public const string Schema = "academic";

    public DbSet<Specialization> Specializations => Set<Specialization>();
    public DbSet<Domain> Domains => Set<Domain>();
    public DbSet<ClassCode> ClassCodes => Set<ClassCode>();
    public DbSet<Semester> Semesters => Set<Semester>();
    public DbSet<RegistrationRound> RegistrationRounds => Set<RegistrationRound>();
    public DbSet<Student> Students => Set<Student>();
    public DbSet<StudentSkill> StudentSkills => Set<StudentSkill>();
    public DbSet<Lecturer> Lecturers => Set<Lecturer>();
    public DbSet<LecturerDomain> LecturerDomains => Set<LecturerDomain>();
    public DbSet<Mentor> Mentors => Set<Mentor>();
    public DbSet<MentorDomain> MentorDomains => Set<MentorDomain>();
    public DbSet<ImportBatch> ImportBatches => Set<ImportBatch>();
    public DbSet<SemesterEnrollment> SemesterEnrollments => Set<SemesterEnrollment>();
    public DbSet<RuleSetting> RuleSettings => Set<RuleSetting>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.HasDefaultSchema(Schema);
        modelBuilder.AddOutboxMessages(Schema);

        // Danh mục (rule 12): id integer GENERATED BY DEFAULT AS IDENTITY.
        modelBuilder.Entity<Specialization>(e => { e.ToTable("specializations"); e.HasKey(x => x.Id); e.Property(x => x.Id).UseIdentityByDefaultColumn(); CreatedAt(e.Property(x => x.CreatedAt)); UpdatedAtByTrigger(e.Property(x => x.UpdatedAt)); });
        modelBuilder.Entity<Domain>(e => { e.ToTable("domains"); e.HasKey(x => x.Id); e.Property(x => x.Id).UseIdentityByDefaultColumn(); CreatedAt(e.Property(x => x.CreatedAt)); UpdatedAtByTrigger(e.Property(x => x.UpdatedAt)); });
        modelBuilder.Entity<ClassCode>(e => { e.ToTable("class_codes"); e.HasKey(x => x.Id); e.Property(x => x.Id).UseIdentityByDefaultColumn(); CreatedAt(e.Property(x => x.CreatedAt)); UpdatedAtByTrigger(e.Property(x => x.UpdatedAt)); });

        // Học kỳ, đợt đăng ký (rule 6).
        modelBuilder.Entity<Semester>(e => { e.ToTable("semesters"); e.HasKey(x => x.Id); CreatedAt(e.Property(x => x.CreatedAt)); UpdatedAtByTrigger(e.Property(x => x.UpdatedAt)); });
        modelBuilder.Entity<RegistrationRound>(e => { e.ToTable("registration_rounds"); e.HasKey(x => x.Id); CreatedAt(e.Property(x => x.CreatedAt)); UpdatedAtByTrigger(e.Property(x => x.UpdatedAt)); });

        // Sinh viên, giảng viên, mentor. Email là citext.
        modelBuilder.Entity<Student>(e => { e.ToTable("students"); e.HasKey(x => x.Id); e.Property(x => x.Email).HasColumnType("citext"); CreatedAt(e.Property(x => x.CreatedAt)); UpdatedAtByTrigger(e.Property(x => x.UpdatedAt)); });
        modelBuilder.Entity<StudentSkill>(e => { e.ToTable("student_skills"); e.HasKey(x => new { x.StudentId, x.Skill }); UpdatedAtByTrigger(e.Property(x => x.UpdatedAt)); });
        modelBuilder.Entity<Lecturer>(e => { e.ToTable("lecturers"); e.HasKey(x => x.Id); e.Property(x => x.Email).HasColumnType("citext"); e.Property(x => x.MaxTeamsExe101).HasColumnName("max_teams_exe101"); e.Property(x => x.MaxTeamsExe201).HasColumnName("max_teams_exe201"); CreatedAt(e.Property(x => x.CreatedAt)); UpdatedAtByTrigger(e.Property(x => x.UpdatedAt)); });
        modelBuilder.Entity<LecturerDomain>(e => { e.ToTable("lecturer_domains"); e.HasKey(x => new { x.LecturerId, x.DomainId }); });
        modelBuilder.Entity<Mentor>(e => { e.ToTable("mentors"); e.HasKey(x => x.Id); e.Property(x => x.Email).HasColumnType("citext"); CreatedAt(e.Property(x => x.CreatedAt)); UpdatedAtByTrigger(e.Property(x => x.UpdatedAt)); });
        modelBuilder.Entity<MentorDomain>(e => { e.ToTable("mentor_domains"); e.HasKey(x => new { x.MentorId, x.DomainId }); });

        // Import (W06–W08) và danh sách sinh viên học kỳ.
        modelBuilder.Entity<ImportBatch>(e => { e.ToTable("import_batches"); e.HasKey(x => x.Id); e.Property(x => x.Errors).HasColumnType("jsonb"); CreatedAt(e.Property(x => x.CreatedAt)); });
        modelBuilder.Entity<SemesterEnrollment>(e => { e.ToTable("semester_enrollments"); e.HasKey(x => x.Id); CreatedAt(e.Property(x => x.CreatedAt)); });

        // Cấu hình quy tắc (W05): một dòng, id = 1 do ứng dụng gán.
        modelBuilder.Entity<RuleSetting>(e => { e.ToTable("rule_settings"); e.HasKey(x => x.Id); e.Property(x => x.Id).ValueGeneratedNever(); UpdatedAtByTrigger(e.Property(x => x.UpdatedAt)); });

        // Khóa ngoại – để EF ghi đúng thứ tự (bảng cha trước) và khớp hành vi xóa của DB script.
        modelBuilder.Entity<RegistrationRound>().HasOne<Semester>().WithMany().HasForeignKey(x => x.SemesterId).HasConstraintName("fk_registration_rounds_semester").OnDelete(DeleteBehavior.Restrict);
        modelBuilder.Entity<Student>().HasOne<Specialization>().WithMany().HasForeignKey(x => x.SpecializationId).HasConstraintName("fk_students_specialization").OnDelete(DeleteBehavior.Restrict);
        modelBuilder.Entity<StudentSkill>().HasOne<Student>().WithMany().HasForeignKey(x => x.StudentId).HasConstraintName("fk_student_skills_student").OnDelete(DeleteBehavior.Cascade);
        modelBuilder.Entity<LecturerDomain>().HasOne<Lecturer>().WithMany().HasForeignKey(x => x.LecturerId).HasConstraintName("fk_lecturer_domains_lecturer").OnDelete(DeleteBehavior.Cascade);
        modelBuilder.Entity<LecturerDomain>().HasOne<Domain>().WithMany().HasForeignKey(x => x.DomainId).HasConstraintName("fk_lecturer_domains_domain").OnDelete(DeleteBehavior.Restrict);
        modelBuilder.Entity<Mentor>().HasOne<Lecturer>().WithMany().HasForeignKey(x => x.LecturerId).HasConstraintName("fk_mentors_lecturer").OnDelete(DeleteBehavior.SetNull);
        modelBuilder.Entity<MentorDomain>().HasOne<Mentor>().WithMany().HasForeignKey(x => x.MentorId).HasConstraintName("fk_mentor_domains_mentor").OnDelete(DeleteBehavior.Cascade);
        modelBuilder.Entity<MentorDomain>().HasOne<Domain>().WithMany().HasForeignKey(x => x.DomainId).HasConstraintName("fk_mentor_domains_domain").OnDelete(DeleteBehavior.Restrict);
        modelBuilder.Entity<ImportBatch>().HasOne<Semester>().WithMany().HasForeignKey(x => x.SemesterId).HasConstraintName("fk_import_batches_semester").OnDelete(DeleteBehavior.Restrict);
        modelBuilder.Entity<SemesterEnrollment>().HasOne<Semester>().WithMany().HasForeignKey(x => x.SemesterId).HasConstraintName("fk_semester_enrollments_semester").OnDelete(DeleteBehavior.Restrict);
        modelBuilder.Entity<SemesterEnrollment>().HasOne<Student>().WithMany().HasForeignKey(x => x.StudentId).HasConstraintName("fk_semester_enrollments_student").OnDelete(DeleteBehavior.Restrict);
        modelBuilder.Entity<SemesterEnrollment>().HasOne<ClassCode>().WithMany().HasForeignKey(x => x.ClassCodeId).HasConstraintName("fk_semester_enrollments_class_code").OnDelete(DeleteBehavior.Restrict);
        modelBuilder.Entity<SemesterEnrollment>().HasOne<ImportBatch>().WithMany().HasForeignKey(x => x.ImportBatchId).HasConstraintName("fk_semester_enrollments_import_batch").OnDelete(DeleteBehavior.SetNull);
    }

    /// <summary>Cột <c>created_at</c> có DEFAULT now(): EF để DB ghi khi giá trị chưa gán.</summary>
    private static void CreatedAt(PropertyBuilder<DateTimeOffset> property) =>
        property.HasDefaultValueSql("now()");

    /// <summary>Trigger <c>set_updated_at</c> ghi cột này; EF đọc lại sau khi lưu.</summary>
    private static void UpdatedAtByTrigger(PropertyBuilder<DateTimeOffset> property) =>
        property.HasDefaultValueSql("now()").ValueGeneratedOnAddOrUpdate();
}
